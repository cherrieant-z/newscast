_SOURCE_TAIL_RE = re.compile(
    r"[（(]\s*(新浪财经|36氪|极客公园|爱范儿|少数派|量子位|InfoQ|参考消息|中新网|新华网|钛媒体|虎嗅)[^）)]{0,10}[）)]"
)


