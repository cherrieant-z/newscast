class NewsSummarizer:
    """
    负责将多源资讯合成为：
    1. 结构化 Markdown 报告（含金句 + 一人公司拆解 + AI 前沿 + 宏观大势 + 原始要闻清单留档）
    2. 「只听就够」的普通话播报底稿：所有值得知道的内容都会念出来，
       不留任何「去页面看」的尾巴；同时给出章节切分，供前端做跳转。
    """

    # 最近一次生成的章节切分：[{label, text}]，由 _build_spoken_script 写入
    last_chapters: List[Dict[str, str]] = []

    async def generate_report(self, date_str: str, collected_data: Dict[str, List[Dict[str, Any]]], recent_leads: List[str] = None, used_quotes: List[str] = None) -> Tuple[str, str, str, str, List[Dict[str, str]], Dict[str, str]]:
        """
        返回: (title, lead_title, markdown_content, tts_script, sources, category_summary)

        recent_leads: 历史上用过的一人公司案例标题。案例现在优先取当天真实项目，
                      这份历史用来保证「同一个项目不会讲两遍」。
        used_quotes:  历史上已经说过的金句，避免每天同一句。
        """
        # 整篇重写会丢掉章节结构和行情卡（前端按固定结构渲染），
        # 所以只保留给显式开启的人；日常一律走下面的结构化生成。
        if settings.LEGACY_LLM_REWRITE and settings.OPENAI_API_KEY:
            try:
                return await self._generate_with_llm(date_str, collected_data)
            except Exception as e:
                print(f"[Summarizer] LLM 整篇重写受阻，改用结构化播报引擎: {e}")

        return await self._generate_curated(date_str, collected_data, recent_leads, used_quotes)

    async def _pick_case(self, date_str: str, recent_leads: List[str] = None,
                         opc_items: List[Dict[str, Any]] = None) -> Dict[str, Any]:
        """
        今天的案例从哪来：只从当天真实项目里挑，挑不到就不做这一段。

        固定案例库已经不参与挑选了。它跟当天真实发生的事没有任何关系，
        本质上就是把同一批故事换个日子重播一遍——这正是听众说「似曾相识」的来源。
        宁可这天没有案例段，也不拿旧故事凑数。

        另一个门槛：帖子必须能看出「怎么收钱 / 有没有人付钱」。
        纯功能分享（我做了个剪切板工具）放进动态列表就够了，
        硬拆成案例只会念出三句「作者没细说」，听众一听就知道在凑时长。
        """
        recent = [t for t in (recent_leads or []) if t]

        cands = [
            it for it in (opc_items or [])
            if not it.get("is_fallback") and it.get("title")
            and not any(is_similar_title(it["title"], r) for r in recent)
            and _has_money_signal(it.get("raw_text") or "")
        ]
        if cands:
            def _score(it: Dict[str, Any]) -> int:
                raw = it.get("raw_text") or ""
                low = raw.lower()
                s = 0
                # 叙述型优先：有正常标点的帖子才拆得出「他为什么做、怎么收钱」。
                # 纯功能罗列（整段没标点）抽出来全是碎片，念着像机器在念说明书。
                # 英文帖子用的是 . ! ? 和空格，只数中文标点会把它们全判成碎片。
                s += min(len(re.findall(r"[。！？，、；]|[.!?](?:\s|$)", raw)), 8)
                if CASE_NUMBER_RE.search(raw):
                    s += 3
                if any(k in raw for k in CASE_PRICE_SIGNALS):
                    s += 3
                if any(w in low for w in CASE_TOOL_WORDS):
                    s += 1
                # 标题本身不完整（「我做了这个…」「这种 xx 有人有兴趣吗」）的，
                # 念出来听众根本不知道在说什么，宁可让位给标题清楚的帖子
                t = it.get("title") or ""
                if "..." in t or "…" in t or re.search(r"(这个|它|这些)\s*$", t) or len(t) < 8:
                    s -= 5
                return s + min(len(raw) // 150, 4)

            cands.sort(key=_score, reverse=True)
            picked = cands[0]
            # 案例会详细讲一遍，动态列表里就不该再出现同一条，
            # 否则听众会在同一期里把同一件事听两次。
            try:
                opc_items.remove(picked)
            except ValueError:
                pass
            return await self._case_from_item(picked, date_str)

        # 今天没有能看出「怎么收钱」的真实项目，就不讲案例。
        # 固定库留着做历史存档（旧链接还能打开），但不再拿来填今天的节目。
        return None

    async def _case_from_item(self, item: Dict[str, Any], date_str: str) -> Dict[str, Any]:
        """
        优先让模型读懂这条帖子；模型不可用或结果不可信，退回规则抽取。

        「不可信」有明确判据：出现原文没有的数字，直接作废。
        案例里一个编造的价格，比没有案例更伤——听众照着去试，会被现实打回来。
        """
        if llm.enabled:
            case = await self._case_with_llm(item)
            if case:
                return case
        return self._case_from_item_rules(item, date_str)

    async def _case_with_llm(self, item: Dict[str, Any]) -> Dict[str, Any] | None:
        raw = re.sub(r"https?://\S+", " ", item.get("raw_text") or item.get("summary") or "")
        raw = re.sub(r"\s+", " ", raw).strip()
        title = _clean_case_title(item.get("title", ""))
        if len(raw) < 60 or not title:
            return None

        data = await llm.json(
            CASE_SYSTEM,
            f"标题：{title}\n\n正文：{raw[:1800]}",
            temperature=0.4,
            max_tokens=900,
        )
        if not data:
            return None

        fields = {
            k: llm_clean(data.get(k), 110)
            for k in ("what", "who_pays", "money", "traction", "startup", "barrier", "first_step")
        }
        # 前三段是「钱」，缺一段就说明原文信息不够拆解，退回规则版反而更诚实。
        if not fields["who_pays"] or not fields["money"]:
            return None
        for key, value in fields.items():
            if _has_invented_number(value, raw):
                print(f"[Summarizer] 案例的「{key}」出现原文没有的数字，已退回规则抽取")
                return None

        # 「今天第一步」是这一节存在的理由。写不出一个能落到手上的动作，
        # 这段就退化成了「别人很厉害」，不如不给。
        if (not _looks_like_action(fields["first_step"])
                or _is_self_promo(fields["first_step"])
                or _needs_product_premise(fields["first_step"])):
            print(f"[Summarizer] 案例的「first_step」不像听众能自用的动作，用规则版兜底："
                  f"{fields['first_step'][:40]}")
            fields["first_step"] = self._guide_for(title, raw)

        return {
            "title": title,
            "what": fields["what"],
            "quote": llm_clean(data.get("quote"), 40),
            "pain_point": fields["who_pays"],
            "model": fields["money"],
            "tech_stack": "",
            "revenue": fields["traction"] or "更具体的进账他没公开。",
            "startup": fields["startup"],
            "barrier": fields["barrier"],
            "guide": fields["first_step"],
            "is_real": True,
            "url": item.get("url", ""),
            "source_name": item.get("source_name", ""),
            "by_llm": True,
        }

    def _case_from_item_rules(self, item: Dict[str, Any], date_str: str) -> Dict[str, Any]:
        """
        把一条真实帖子拆成五段播报素材。

        每一段要么引用原文，要么明确说「没写」——
        绝不生成原文里没有的数字。案例可以朴素，但不能假。
        """
        title = _clean_case_title(item.get("title", ""))
        raw = re.sub(r"https?://\S+", " ", item.get("raw_text") or item.get("summary") or "")
        raw = re.sub(r"\s+", " ", raw).strip()
        sents = _split_sentences(raw)

        # 1) 解决什么麻烦：优先找作者自己讲「原来多麻烦」的句子
        pain = ""
        for kw in ("痛点", "麻烦", "每次", "以前", "原来", "一直", "找不到", "手动", "重复", "受够"):
            pain = next((s for s in sents if kw in s), "")
            if pain:
                break
        if not pain:
            # 帖子里没写动机就不编。
            # 用正文里第一句有效描述代替「他为了解决什么痛点」这种硬套的说法。
            if sents:
                pain = f"帖子里没细讲为什么做，只说了它大概是这样的：{_cut(sents[0], 60)}"
            else:
                pain = "帖子里没细说，除了标题基本没有别的描述。"

        # 2) 收钱：原文真的提到价格/订阅才引用
        money = next((s for s in sents if s != pain and any(k in s for k in CASE_PRICE_SIGNALS)), "")
        if money:
            model = _cut(money)
        elif "免费使用" in raw or "完全免费" in raw:
            model = "目前还是免费用的，作者没提后面打算怎么收钱。"
        else:
            model = "作者没提收费，现在更像是在验证到底有没有人真的需要它。"

        # 3) 工具：只认原文里出现过的名字
        low = raw.lower()
        tools: List[str] = []
        for w in CASE_TOOL_WORDS:
            if w not in tools and re.search(rf"(?<![a-z]){re.escape(w)}(?![a-z])", low):
                tools.append(w)
        stack = ("他用到的是：" + "、".join(t.capitalize() if t.isascii() else t for t in tools[:4]) + "。") \
            if tools else "作者没细说拿什么做的。"

        # 4) 收入：必须同时出现数字和「钱」相关的词。
        #    否则会把「每天抓取 500 多个频道」这种规模数字，当成收入念出去。
        #    中文数字（「三十多个付费用户」）抓不到数字，所以再放一条纯措辞通道。
        rev_sents = [
            s for s in sents
            if s not in (pain, money) and (
                (CASE_NUMBER_RE.search(s) and any(k in s for k in REVENUE_CUES))
                or any(k in s for k in ("付费用户", "付费客户", "已经有人付", "有人买单", "覆盖了服务器"))
            )
        ]
        if rev_sents:
            revenue = _cut(rev_sents[0])
        elif money:
            revenue = "更具体的进账作者还没公开，从上面说的定价看，还处在刚开始收钱的阶段。"
        else:
            revenue = "作者没公开收入，这条目前是「做出来了」，还不是「赚到了」。"

        # 5) 起步要准备什么：只认原文提到的成本线索，没有就给「不花钱也能验证」的路子。
        #    已经拿去讲收入的句子要排除，否则同一句话会被念两遍。
        already_used = {pain, money, revenue}
        cost_sents = [
            s for s in sents
            if s not in already_used
            and any(k in s for k in ("成本", "免费", "开源", "不用花钱", "自己搭", "花了", "投入"))
        ]
        if cost_sents:
            startup = _cut(cost_sents[0], 70)
        else:
            startup = ("他没写自己花了多少。这类东西的好处是不用先囤货、不用租店面，"
                       "先用现成的免费额度把第一版跑通，验证有人要再谈投入。")

        # 6) 难在哪：原文自己说过「最难的是……」就直接引，比规则判断准
        hardest = next(
            (s for s in sents if s not in already_used
             and any(k in s for k in ("最难", "难度", "门槛", "不容易", "卡在", "麻烦的是"))),
            "",
        )
        barrier = _cut(hardest, 70) if hardest else self._barrier_for(title, raw)

        # 7) 今天第一步：规则版一直给的是具体动作，直接复用
        guide = self._guide_for(title, raw)

        return {
            "title": title,
            "what": _fallback_what(title, item.get("summary") or raw),
            "quote": "",
            "pain_point": pain,
            "model": model,
            "tech_stack": stack,
            "revenue": revenue,
            "startup": startup,
            "barrier": barrier,
            "guide": guide,
            "is_real": True,
            "url": item.get("url", ""),
            "source_name": item.get("source_name", ""),
        }

    def _barrier_for(self, title: str, raw: str) -> str:
        """这件事真正的难处。按类型给，避免每天都念「门槛不高但要坚持」"""
        t = (title + " " + raw[:240]).lower()
        if any(k in t for k in ("小程序", "插件", "脚本", "cli", "小工具", "工具")):
            return "难的不是写出来，是让人知道你写了。做出来只是第一天的事，后面全在找那批人。"
        if any(k in t for k in ("网站", "平台", "榜单", "导航", "社区")):
            return "难在数据要天天更新，停一周就没人来了。一个人做这类东西，拼的是更新不断，不是功能多。"
        if any(k in t for k in ("游戏", "小游戏")):
            return "难在没人替你传播。玩法做得再好，没有让人想截图分享的那一下，就只是一个自己玩的东西。"
        if any(k in t for k in ("ai", "gpt", "智能体", "大模型", "agent")):
            return "难在你得先知道哪个环节真的在浪费时间。技术不是门槛，找对那个环节才是。"
        return "难在坚持用它解决自己的问题。多数人卡在做出来之后不知道给谁用，而不是卡在做不出来。"

    def _guide_for(self, title: str, raw: str) -> str:
        """
        按项目类型给「你能抄的那部分」。

        全部写成调查型动作，而不是「去做一个产品」型动作：听众多半手上还没有
        任何产品，任何以「你的产品后台」为前提的建议，他今天都做不了。
        调查型动作今天就能做，而且做完手里就有东西（一份抱怨清单、一句痛点）。
        """
        t = (title + " " + raw[:240]).lower()
        if any(k in t for k in ("小程序", "插件", "脚本", "cli", "小工具", "工具")):
            return ("去应用商店翻三个同类工具的差评，只记重复出现的那条抱怨。"
                    "重复三次以上的，就是有人愿意为解决它掏钱的信号；"
                    "只有一条的，是你自己觉得有意思，不是市场觉得。")
        if any(k in t for k in ("网站", "平台", "榜单", "导航", "社区")):
            return ("打开这个领域现有的三个网站，各看一眼：它们每天更新什么、靠什么收钱、"
                    "哪一块做得最敷衍。敷衍的那块通常就是留给后来者的口子。")
        if any(k in t for k in ("游戏", "小游戏")):
            return ("去玩三个同类小游戏，一边玩一边记你在第几分钟想关掉。"
                    "记满三个，你就知道这类东西真正的生死线在哪，比想功能有用。")
        if any(k in t for k in ("ai", "gpt", "智能体", "大模型", "agent")):
            return ("打开你每天用得最多的三个软件，各找一个让你烦的步骤，写成一句话。"
                    "三句话里如果有两句在说同一件事，那就是你该动手的地方。")
        return ("打开备忘录，写下你今天重复做了三遍以上的一件事，以及它卡在哪一步。"
                "写不出来，说明你要做的需求是你想象出来的；写得出来，那就是起点。")

    def _pick_quote(self, used: List[str] = None) -> str:
        """今日金句（规则版）：优先挑这个节目里还没说过的"""
        used = [u for u in (used or []) if u]
        fresh = [q for q in DAILY_QUOTES if not any(is_similar_title(q, u) for u in used)]
        return fresh[0] if fresh else DAILY_QUOTES[0]

    async def _quote_from_today(self, collected_data: Dict[str, List[Dict[str, Any]]],
                               used: List[str] = None) -> str:
        """
        让模型看着今天的具体内容写一句，而不是从固定句库里轮流取。

        固定库只有 24 句，按「还没说过」往后取，等于 24 天一轮回；
        而且它跟今天讲的事没关系，放在任何一天都成立——这本身就是重复的来源。
        写不出来就返回空，调用方退回固定库。
        """
        if not llm.enabled:
            return ""
        titles = [it.get("title", "") for cat in ("AI Agent", "一人公司")
                  for it in (collected_data.get(cat) or [])][:8]
        if not titles:
            return ""
        used = [u for u in (used or []) if u][-8:]
        data = await llm.json(
            QUOTE_SYSTEM,
            "今天要讲的内容：\n" + "\n".join(f"- {t}" for t in titles)
            + ("\n\n这些是这个节目以前说过的，不要重复：\n" + "\n".join(f"- {u}" for u in used) if used else ""),
            temperature=0.95,
            max_tokens=200,
        )
        quote = llm_clean((data or {}).get("quote"), 40)
        if not quote or not has_cjk(quote) or len(quote) < 8:
            return ""
        if any(is_similar_title(quote, u) for u in used):
            return ""
        return quote

