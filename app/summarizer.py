def _looks_like_action(text: str) -> bool:
    """这段是不是一个真能做的动作，而不是一句正确的废话"""
    t = (text or "").strip()
    if len(re.sub(r"\s", "", t)) < 12:
        return False
    if any(w in t for w in EMPTY_ADVICE):
        return False
    if any(w in t for w in ("作者没", "原文没", "未披露", "没有公开")):
        return False
    return any(v in t for v in ACTION_VERBS)


