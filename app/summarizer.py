# ------------------------------------------------------------ 口播：把「看的字」变成「听的话」
#
# 这一层的存在理由：稿子是给人耳朵听的，听众看不到标点、括号、段落、加粗。
# 所有靠排版表达的主次关系，在音频里都必须变成词——否则听众听到的是一串
# 没有层次的名词，听完不知道刚才那段在说什么。
#
# 另外，每天用同一句开场和同一个转折，听三天就能预判下一句，这是「体感差」
# 的主要来源。所以这里所有固定句式都走 _day_pick 按日期轮换。

# 「作者没写」这类话，说一次是诚实，说三次是敷衍
