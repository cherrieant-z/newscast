def macro_reading(domain: str, title: str) -> Tuple[str, str]:
    """返回 (这意味着什么, 你该怎么做)"""
    cfg = MACRO_READING.get(domain)
    if not cfg:
        return "", ""
    t = (title or "").lower()
    for kws, meaning, action in cfg["cues"]:
        if any(_cue_hit(t, k) for k in kws):
            return meaning, action
    return cfg["default"]


