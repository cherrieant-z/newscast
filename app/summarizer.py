# 同一个意思绕着说：「用它的人能按月付钱」——把「按月收费」换个说法讲一遍。
# 句式对、字数对、也没踩黑名单，但听众听完不知道这工具到底干什么。
# 判据：主语 + 能/可以 + 还是那批抽象动作（付钱、订阅、使用、获得），
# 而不是一个具体动作（导出订单、识别二维码、查库存）。
HOLLOW_TAIL = re.compile(
    r"(?:用它的人|用它的人|用户|你|他|她)(?:能|可以|能够|就能)"
    r"(?:按月|按年|按次|随时)?"
    r"(?:付钱|付费|付款|订阅|购买|获得|得到|享受|使用|用上)"
)

# 循环定义：把「谁」和「为什么」用自己的话再说一遍，等于什么也没说。
# 「愿意每月掏五百美元的小团队，为的是解决那个让他愿意长期付钱的麻烦」——
# 主语是「愿意付钱的人」，谓语是「为了解决他愿意付钱的那个麻烦」。
HOLLOW_CIRCULAR = re.compile(
    r"为(?:的)?是.{0,14}(?:麻烦|问题|需求|痛点)|"
    r"为了.{0,10}(?:解决|满足|应对).{0,12}(?:麻烦|问题|需求|痛点)"
)

# 剥掉抽象词之后还剩多少种不同的字。
# 「一个按月收费的订阅服务，帮小团队做某件具体的事」剩 9 种；
# 「这是一个给石材商用的实时库存系统，扫一下板子就知道在哪」剩 26 种。
# 中间隔着十几倍，是最稳的一条判据——黑名单永远追不上模型换说法的速度。
HOLLOW_ABSTRACT = re.compile(
    r"服务|价值|客户|用户|需求|工具|平台|方案|产品|功能|体验|效率|场景|"
    r"方式|模式|内容|能力|东西|业务|项目|系统|应用|订阅|付钱|付费|收费|"
    r"麻烦|问题|团队|某些?|某件|某类|具体|帮助|解决|提供|实现|支持|"
    r"管理|处理|长期|持续|按|每月|某个|一个|这个"
)

# 判「谁做的」是不是白说。「一个独立开发者」七个字，长短完全合格，
# 但听众听完不知道多任何一件事。少于这个词表以外的实义字，就不念这句。
WHO_FILLER = re.compile(
    r"^(他|她|作者|这个人)?(是)?(一[个位名]|一名)?"
    r"(独立开发者|独立开发人员|开发者|程序员|工程师|小团队|团队|个人|人|创业者)$")
WHO_FILLER_CHARS = set("一个位名他她作者是独立开发员工程序团队个人的")


def _hollow(text: str) -> bool:
    """这段是不是「通顺的空话」。"""
    body = (text or "").strip()
    if not body:
        return True
    if any(k in body for k in HOLLOW_MARKS):
        return True
    if HOLLOW_TAIL.search(body) or HOLLOW_CIRCULAR.search(body):
        return True
    # 兜底一条：把所有抽象名词和套话剥掉，看还剩几种字。
    # 剩下太少，说明这段只是把「服务 / 客户 / 价值」这几个词翻来覆去排列。
    # 只对长句生效：短句本来就字少，「记账工具，自动整理发票」剥完只剩八个字，
    # 但那八个字是实打实的。
    core = HOLLOW_ABSTRACT.sub("", body)
    core = re.sub(r"[，。、；：,.;:！？!?\s]", "", core)
    if _spoken_len(body) < 22:
        return False
    return len(set(core)) <= 11


def _generic_who(text: str) -> bool:
    """「一个独立开发者」这种不提供任何信息的身份描述。"""
    if _hollow(text):
        return True
    body = re.sub(r"[\s，。、；：,.;:！？!?]", "", text or "")
    if not body:
        return True
    if WHO_FILLER.match(body):
        return True
    # 去掉「一个 / 独立 / 开发者」这类通用词之后，还剩几个字。
    # 剩下不到 4 个不同字，说明除了身份标签什么都没有。
    core = {c for c in body if c not in WHO_FILLER_CHARS}
    return len(core) < 4


def _case_ok(case: Dict[str, Any] | None) -> bool:
    """
    这条拆出来能不能让听众听懂。

    判据只有一条但很硬：第一句必须说得出具体的东西。
    「一个叫不出名字的在线工具」这种开头，后面补多少信息都救不回来——
    听众脑子里连一个名词都没挂住，剩下的全是从耳朵流过去的水。
    今天那条去人声工具就是这么翻车的。

    第二种翻车方式更隐蔽：把标题当「这是什么」念一遍。
    「照片不上传的免费压缩工具」不是一句介绍，是标题，听众听完还是不知道
    它叫什么、是网页还是软件。
    """
    if not case:
        return False
    what = (case.get("what") or "").strip()
    # 14 字是下限：「这是一个在线工具」正好卡在线上，「这是一个付费订阅服务，
    # 用户按月付费」够。短于此的基本都是「一个 xxx 工具」的标题式复述。
    if _spoken_len(what) < 14:
        return False
    if any(k in what for k in VAGUE_NAME):
        return False
    # 只拦「几乎就是标题」的情况。what 比标题长一倍以上，说明它在展开，
    # 哪怕用词重合得多也算讲清楚了——「QR Right-Click 是一个 Chrome 插件，
    # 装上之后在网页图片上点右键就能识别二维码」就是这种。
    if _spoken_len(what) <= _spoken_len(case.get("title") or "") * 1.2 \
            and is_similar_title(what, case.get("title") or ""):
        return False
    return True


def _strip_negated(text: str) -> str:
    """
    删掉「没有付费用户」「不收钱」这类否定分句。

    判「有没有人付钱」时最容易被否定句骗：一句「完全免费，不收钱」里
    同时出现「免费」和「收费」，按关键词匹配会得出「他在收钱」的结论。
    """
    kept = []
    for sent in re.split(r"(?<=[。！？])", text or ""):
        if not sent.strip():
            continue
        if re.search(r"(没有|没人|不曾|并不|不是|不收|不收费|未|无)", sent) and \
                re.search(r"(付费|收费|订阅|价格|定价|收入|买单|revenue|paid|pricing)", sent, re.I):
            continue
        kept.append(sent)
    return "".join(kept)


def _payer_signal(raw: str) -> str:
    """
    原文能不能看出「有人真的掏了钱」。三个值：有 / 没有 / 没写。

    这是案例分档的唯一依据。`_has_money_signal` 只能说明「提到了钱」，
    提到钱不等于赚到钱——今天这条插件提到「5 美元注册费」「免费开源」，
    旧判据把它当成了有钱的案例，结果整段没法讲。
    """
    t = _strip_negated(raw or "")
    low = t.lower()
    if any(k in t for k in PAID_PROOF_CN) or any(k in low for k in PAID_PROOF_EN):
        return "有"
    if re.search(r"(完全免费|免费使用|永久免费|开源|不收费|不收钱|open.?source|it'?s free)", low):
        return "没有"
    if re.search(r"(收费|定价|价格|订阅|月费|年费|price|pricing|subscription)", low):
        return "没写"
    return "没写"


def _has_ops_number(raw: str) -> bool:
    """有没有真实运营数字（安装量、用户数、下载量）。反面样本全靠这个立住。"""
    return bool(re.search(
        r"\d{2,7}\s*(?:次|个|位|名|人)?\s*(?:安装|下载|用户|访问|订阅|注册)"
        r"|(?:安装|下载|用户|访问)\D{0,4}\d{2,7}"
        r"|\d{2,7}\s*(?:installs?|users?|signups?|visits?)", raw or "", re.I))


def _case_age_days(published: str) -> int | None:
    """
    这条帖子是几天前发的。解析不出日期就返回 None，不参与新鲜度打分。

    案例池的窗口有一个月，池子里躺着的都是能讲的故事。但同样能讲的两条，
    应该先讲今天刚发的——三周前的帖子多半已经在别处被讲透了。
    """
    raw = (published or "").strip()
    if not raw:
        return None
    dt = None
    try:
        dt = email.utils.parsedate_to_datetime(raw)
    except Exception:
        dt = None
    if dt is None:
        try:
            dt = datetime.datetime.fromisoformat(raw.replace("Z", "+00:00"))
        except Exception:
            return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=datetime.timezone.utc)
    return max(0, (datetime.datetime.now(datetime.timezone.utc) - dt).days)


def _case_kind(case: Dict[str, Any]) -> str:
    """
    这一节该按「赚钱案例」讲，还是按「反面样本」讲。

    今天这条 Chrome 插件是免费开源的，没人付过钱，周活 7 个，却被开场说成
    「先给你一个可抄的例子」——听众听三分钟也不知道在抄什么。问题不在话术，
    在于把一个没有商业模式的东西放进了「搞钱案例」的位置。

    所以先分档：
    - money：原文里有付费用户数、订阅收入、MRR 这类硬证据
    - sample：做出来了，但原文明确写了没做成（没人用、放弃、关掉）
    - howto：两样都没有，但这条路本身讲得清——按「能抄的做法」讲，
      开场第一句就说明白，不装成赚钱故事，也不替人下「他失败了」的结论

    分档之后开场、结构、用词全部跟着变，听众的预期才不会落空。
    """
    if (case.get("kind") or "") == "howto":
        return "howto"
    if (case.get("paid") or "").strip().startswith("有"):
        return "money"
    blob = " ".join(str(case.get(k) or "") for k in
                    ("pain_point", "model", "revenue")).lower()
    if any(k in blob for k in PAID_PROOF_CN) or any(k in blob for k in PAID_PROOF_EN):
        return "money"
    # 没有付费证据，不等于失败。刚上线的产品谁都还没付钱，
    # 把它说成「反面样本」，听众会觉得节目在替人下结论——
    # 「这东西没人用」这句话，原文没写就不能说。
    fail_blob = " ".join(str(case.get(k) or "") for k in
                         ("pain_point", "revenue", "barrier", "what")).lower()
    if any(k in fail_blob for k in CASE_FAIL_SIGNALS):
        return "sample"
    return "howto"


def _ratio_line(text: str) -> str:
    """
    把后台那两个数字翻成人话。

    「安装 188 次，周活 7 个」单独念，听众没有参照系——188 算多还是少？
    算成「每一百个装过的人里，只有 4 个还在用」，耳朵立刻能判断这生意成没成。
    这一步不做，案例就永远是一串听不懂的数字。
    """
    t = text or ""
    inst = re.search(r"(?:安装请求|安装量|安装|下载量|下载)\D{0,4}(\d{2,7})\s*次", t) \
        or re.search(r"(\d{2,7})\s*次(?:安装|下载)", t)
    act = re.search(r"(?:周活|周活跃|月活|月活跃|日活)\D{0,4}(\d{1,6})\s*个?", t)
    if not (inst and act):
        return ""
    i, a = int(inst.group(1)), int(act.group(1))
    if i <= 0 or a <= 0 or a >= i * 0.5:
        return ""
    pct = a * 100 / i
    if pct >= 1:
        return f"换个说法，每一百个装过的人里，只有 {max(1, round(pct))} 个这一周还打开过。"
    return "换个说法，装过的人里，一百个人中连一个都留不下来。"


# 「有人真的掏过钱」的硬证据。
# 只认「钱进来了」的说法：「注册费」「上架费」「服务器成本」是作者花出去的，
# 不能算商业模式——今天这条插件就是靠「5 美元一次性注册费」被判成有钱的。
PAID_PROOF_CN = ("付费用户", "付费客户", "付费订阅", "有人付了", "有人买单",
                 "已经开始收钱", "月收入", "年收入", "订阅收入", "客单价", "营收")
PAID_PROOF_EN = ("paying customer", "paying user", "mrr", "arr", "revenue",
                 "subscribers", "paid plan", "conversion to paid")

# 「这事没做成」的明确说法。只有原文真的这么写，才允许把案例叫「反面样本」。
# 没有这段判据，任何一条还没开始收钱的新品都会被说成「失败的例子」——
# 那是节目替作者下结论，听众一听就知道在硬套模板。
CASE_FAIL_SIGNALS = (
    "没人用", "没人买", "没人下载", "没人付", "零用户", "没有用户",
    "放弃了", "关掉了", "关停了", "做不下去", "撑不住", "砍掉了", "失败了",
    "留存很低", "几乎没人", "只有几个人",
    "no users", "zero users", "gave up", "shut down", "shutting down",
    "failed", "didn't work", "flop", "abandoned", "sunset", "almost no",
)


def _looks_like_revenue(model: str) -> bool:
    """
    这段讲的是「钱怎么进来」还是「钱怎么花出去」。

    「上架时交了 5 美元一次性注册费，不年费不抽成」是成本，不是商业模式。
    把它当收钱方式讲，听众会以为这个插件靠注册费赚钱——恰好相反。
    所以只认明确的收入动词，认不出来就按「没有商业模式」处理。
    """
    # 先剔掉「不年费」「不抽成」「不是订阅」这类否定说法，否则「不抽成」里的
    # 「抽成」会把一段讲成本的话判成讲收入
    t = re.sub(r"不[^，。！？]{0,4}(年费|抽成|收费|收钱|订阅|赚钱|变现)", "", model or "")
    return any(k in t for k in ("订阅", "买断", "按次", "按月", "按年", "年付",
                                "收费", "卖掉", "卖", "定价", "付费用户", "付费客户",
                                "会员费", "广告位", "佣金", "抽佣", "分成"))


# 规则版的兜底话术。它们读起来通顺、听着像人话，但不含任何信息——
# 「作者没公开收入，这条目前是『做出来了』，还不是『赚到了』」。
# 这些句子最大的危害不是占时间，是让判断「这段有没有料」的代码以为它有料。
FILLER_MARKS = (
    "帖子里没细讲", "帖子里没细说", "他没写自己花了多少", "这类东西的好处是不用先囤货",
    "作者没公开收入", "还不是「赚到了」", "作者没提收费", "更具体的进账",
    "现在更像是在验证", "先用现成的免费额度把第一版跑通",
)


def _strip_filler(text: str) -> str:
    """剔掉兜底话术，只留原文里真有的东西。"""
    kept = []
    for sent in re.split(r"(?<=[。！？])", text or ""):
        if not sent.strip():
            continue
        if any(k in sent for k in FILLER_MARKS):
            continue
        kept.append(sent)
    return "".join(kept)


def _case_has_substance(pain: str, model: str, rev: str = "", kind: str = "money") -> bool:
    """
    这个案例有没有拆的价值。

    「他没写谁在掏钱」+「他没写怎么收钱」两条一起出现，这段就只剩四句
    「没写」，等于占两分钟告诉听众没什么可说。这种情况宁可今天不做案例。

    反面样本（没人付钱）的判断标准不同：钱那两段天然是空的，它靠的是
    「做到什么程度」或者「客户是谁、麻烦在哪」。

    关键一步是先剔掉规则版的兜底话术再数长度——
    「作者没公开收入，这条目前是『做出来了』，还不是『赚到了』」有 30 个字，
    但它一个字的信息都没有。按字数判，这些空话会一直冒充实料，
    听众听到的就是一连串正确废话。
    """
    pain, model, rev = _strip_filler(pain), _strip_filler(model), _strip_filler(rev)
    if kind == "sample":
        return _spoken_len(rev) >= 15 or _spoken_len(pain) >= 15
    return _spoken_len(pain) >= 12 or _spoken_len(model) >= 12


def _summary_offtopic(title: str, summary: str) -> bool:
    """
    摘要跟标题是不是同一件事。

    源站偶尔把正文开头抓串——今天那条「千问办公押注 Team 智能体」后面
    跟的是一段北欧神话。这种摘要念出来，听众只会觉得节目在胡言乱语。
    判据用最长公共子串：同一件事的摘要至少有 3 个字连续重合。
    """
    if not summary or len(summary) < 16:
        return False
    a = re.sub(r"[^\u4e00-\u9fa5A-Za-z0-9]", "", title or "")
    b = re.sub(r"[^\u4e00-\u9fa5A-Za-z0-9]", "", summary)
    if len(a) < 4 or len(b) < 8:
        return False
    return _lcs_len(a, b) < 3


def _summary_echoes_title(title: str, summary: str) -> bool:
    """摘要只是把标题再说一遍（源站常见），念两遍纯属浪费听众时间。"""
    a = re.sub(r"[^\u4e00-\u9fa5A-Za-z0-9]", "", title or "")
    b = re.sub(r"[^\u4e00-\u9fa5A-Za-z0-9]", "", summary or "")
    if not a or not b:
        return False
    if a in b or b in a:
        return True
    if min(len(a), len(b)) >= 8 and _lcs_len(a, b) >= min(len(a), len(b)) * 0.8:
        return True
    # 标题里的产品名（「」里的词）在摘要里又出现一次，摘要多半只是换个说法
    # 重说一遍：「做了个记录演唱会的 App「也在场」」+「叫「也在场」的那个」
    names = re.findall(r"[「“\"]([^」”\"]{2,12})[」”\"]", title or "")
    if names and any(n in (summary or "") for n in names) and len(summary or "") <= len(title or "") * 2:
        return True
    return False


def _scrub_what(text: str) -> str:
    """
    删掉「具体名字和形态原文没写」这类交代。

    模型很爱在开头补一句「名字没写」，它觉得这是诚实，但听众听到的是
    「主播自己也不知道在讲什么」。答不出名字就直接描述它做什么，
    剩下的半句反而更清楚：「这是一个独立开发者运营的按月收费服务」。
    """
    kept = []
    for part in re.split(r"(?<=[，、；;])", text or ""):
        if any(k in part for k in UNKNOWN_MARKS):
            continue
        # 「打开之后能干什么原文也没细说」「具体名字和形态原文没写」——
        # 各种时态语态的变体，用正则一次盖住
        if re.search(r"(原文|作者|帖子|他)[^，。]{0,6}(没|未|也没|没细)(说|写|提|公开|讲)", part):
            continue
        if re.search(r"(名字|形态|具体叫什么).{0,8}(没写|没提|不知道|不明)", part):
            continue
        kept.append(part)
    out = "".join(kept).strip().rstrip("，、；; ")
    # 删掉中间分句后，会留下「…付费订阅服务，但能让人按月付钱」这种断口。
    # 句子还能听懂，但那个「但」在耳朵里是个坑。
    out = re.sub(r"[，,]?\s*(但|但是|不过|而且|所以|因此|而且)[，,]?", "，", out)
    out = re.sub(r"^[，,]\s*", "", out)
    return out or (text or "").strip()


def _scrub_unknown(text: str) -> str:
    """剔掉「原文没写…」这类分句。听众不知道「原文」是什么，听两句就烦了。"""
    out = []
    for sent in re.split(r"(?<=[。！？])", text or ""):
        if not sent.strip():
            continue
        kept = [c for c in re.split(r"(?<=[，、；;])", sent)
                if not any(k in c for k in UNKNOWN_MARKS)]
        piece = "".join(kept).strip().rstrip("，、；; ")
        if piece:
            out.append(piece if piece.endswith(("。", "！", "？")) else piece + "。")
    return "".join(out)


def _merge_money(model: str, rev: str) -> str:
    """把「怎么收钱」和「赚没赚到」合成一段，并且只允许说一次「他没公开」。"""
    mu = any(k in (model or "") for k in UNKNOWN_MARKS)
    ru = any(k in (rev or "") for k in UNKNOWN_MARKS)
    m = _scrub_unknown(model)
    r = _scrub_unknown(rev)
    if mu and ru:
        return (m.rstrip("。") + "。" if m else "") + "具体进账他没公开。"
    return "".join(x for x in (m, r) if x)


